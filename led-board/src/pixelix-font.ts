export const FONT: CharMap = TOMTHUMB;

export function getChar(ch: string): string[] {
  return FONT[ch] ?? FONT[ch.toUpperCase()] ?? FONT[ch.toLowerCase()] ?? BLANK;
}

export function renderPixelixText(text: string, scale: number = 1): boolean[][] {
  const charHeight = H * scale;
  const rows: boolean[][] = Array.from({ length: charHeight }, () => []);
  for (const ch of text) {
    const pattern = getChar(ch);
    const charWidth = W * scale;
    for (let r = 0; r < charHeight; r++) {
      const srcRow = pattern[Math.floor(r / scale)] || '';
      for (let c = 0; c < charWidth; c++) {
        rows[r].push((srcRow[Math.floor(c / scale)] || ' ') !== ' ');
      }
    }
  }
  return rows;
}